//! 资源额度的记账原语
//!
//! # 这个 crate 现在只剩两件事
//!
//! [槽位池](slot::SlotPool)：把"同时只能有 N 个"变成能借、能还、能看峰值的对象。
//! 三档并发（源端取数单元 / 处理 task / 目标端写入）各持一个。
//!
//! [占用尺子](meter::MemMeter)：连接器把**它自己知道的**常驻内存挂上来，
//! 引擎读峰值 —— 引擎量不到连接器内部（那些缓冲在第三方库里），
//! 而连接器自己知道它要了多少。启动期那本**预测**账（`unit_footprint`）
//! 回答"装不下要不要拒绝启动"，这把尺子回答"那本账准不准"。
//!
//! # 被删掉的那些，以及为什么
//!
//! 这里曾经有 `ResourceBudget`（四本账）、`Admission`（一次拿齐多本账）、
//! `MemoryGate`（字节闸门）、`MemoryPolicy`（背压/拒绝）、`SpillManager`、
//! `TieredMemoryPool`、`GlobalMemoryPool`、`ChildProcessQuota`、`derive_slots`、
//! `per_pipeline_footprint`。
//!
//! 它们被删掉不是"没用上"，而是**它们的因果方向是错的**：
//!
//! ```text
//! 旧：内存额度 ÷ 每单元常驻  =  并发数
//! 新：并发数由用户配置              内存额度只用于**启动期账本校验**
//! ```
//!
//! 旧方向的代价是一连串用户感知不到的行为：配了 32 路并发实际只跑 6 路、
//! "加内存才变快"（于是永远不知道该加内存）、内存与并发的关系是一团黑盒。
//! 新的方向把这两件事彻底分开：
//!
//! - **并发**：用户能感知（数据库能接几个连接），就让他直接配
//! - **内存**：不够时**溢出到磁盘**（`d2d_execution::pool`）或**拒绝启动并说明超在哪一项**，
//!   绝不偷偷砍并发
//!
//! 字节那边的记账搬去了 `d2d_execution::pool::DataPool` —— 它在**池**的层次上
//! 有界、可溢出、可观测，比一个全局字节闸门更贴近真实的内存形状（闸门管不到的
//! 部分——子进程、通道在途——在旧模型里永远是"预算 512MB 却常驻 3GB"的来源）。

pub mod meter;
pub mod slot;

pub use meter::{MemLease, MemMeter, MemSnapshot};
pub use slot::{SlotLease, SlotPool};
